  // Coluna com topo arredondado de 4 px, reta na base.
  const bar = (x, y, w, h, cls) => {
    if (h <= 0) return '';
    const r = Math.min(4, w / 2, h);
    return `<path class="bar ${cls}" d="M${x} ${y + h} V${y + r} Q${x} ${y} ${x + r} ${y} H${x + w - r} Q${x + w} ${y} ${x + w} ${y + r} V${y + h} Z"/>`;
  };
  const width = el => Math.max(300, Math.min(560, el.clientWidth || 560));
  const catName = (spec, c) => spec.catKey && spec.catKey[c] ? t(spec.catKey[c]) : c;

  function plot(spec, W, H) {
    const series = spec.series;
    const padL = 44, padR = 8, padT = 16, padB = 40;
    const plotW = W - padL - padR, plotH = H - padT - padB;
    const slot = plotW / spec.cats.length;
    const gap = 2, barW = Math.min(22, (slot * 0.66 - gap * (series.length - 1)) / series.length);
    const groupW = barW * series.length + gap * (series.length - 1);
    const y = v => padT + plotH - (v / spec.max) * plotH;
    let g = '<g class="grid">';
    for (let v = 0; v <= spec.max + 1e-9; v += spec.step) g += `<line x1="${padL}" x2="${W - padR}" y1="${y(v)}" y2="${y(v)}"/><text x="${padL - 8}" y="${y(v) + 4}" text-anchor="end">${fmt(v, 0)}${spec.unit}</text>`;
    g += '</g>';
    let bars = '', labels = '', cats = '';
    const hits = [];
    spec.cats.forEach((c, i) => {
      const gx = padL + slot * i + (slot - groupW) / 2, cx = padL + slot * i + slot / 2;
      const name = catName(spec, c), short = name.replace('mistral-small', 'mistral').replace('gpt-oss', 'gpt-oss');
      if (slot < 86 && short.includes(':')) {   // tela estreita: nome e tamanho em duas linhas
        const [fam, size] = short.split(':');
        cats += `<text class="cat" x="${cx}" y="${H - 18}" text-anchor="middle">${fam}<tspan x="${cx}" dy="12">${size}</tspan></text>`;
      } else cats += `<text class="cat" x="${cx}" y="${H - 8}" text-anchor="middle">${short}</text>`;
      const parts = [];
      series.forEach((s, k) => {
        const v = spec.values[s.key][i], x = gx + k * (barW + gap);
        if (v == null) return;
        const tp = y(v);
        bars += bar(x, tp, barW, padT + plotH - tp, s.key);
        if (s.key === spec.labelKey && barW >= 11) labels += `<text class="val" x="${x + barW / 2}" y="${tp - 5}" text-anchor="middle">${fmt(v, spec.dec)}</text>`;
        parts.push(`${s.name()} ${fmt(v, spec.dec)}${spec.unit}`);
      });
      hits.push({ x: gx - gap, w: groupW + gap * 2, text: `${name}: ${parts.join(' · ')}` });
    });
    const hitRects = hits.map((h, i) => `<rect class="hit" data-i="${i}" x="${h.x}" y="${padT}" width="${h.w}" height="${plotH}" tabindex="0"><title>${h.text}</title></rect>`).join('');
    const svg = `<svg viewBox="0 0 ${W} ${H}" role="img">${g}<g class="axis"><line x1="${padL}" x2="${W - padR}" y1="${y(0)}" y2="${y(0)}"/></g>${bars}${labels}${cats}${hitRects}</svg>`;
    return { svg, hits };
  }
  const legendOf = series => `<div class="legend">${series.map(s => `<span><i class="sw ${s.key}"></i>${s.name()}</span>`).join('')}</div>`;
  const cell = (v, spec) => v == null ? '—' : fmt(v, spec.dec) + spec.unit;
  function wire(el, hits) {
    const svg = $('svg', el);
    svg.addEventListener('mousemove', ev => { const r = ev.target.closest('.hit'); if (r) showTip(ev, hits[+r.dataset.i].text); else hideTip(); });
    svg.addEventListener('mouseleave', hideTip);
    const table = $('table.twin', el), toggle = $('.toggle', el), plots = $('.plots', el);
    toggle.addEventListener('click', () => { table.hidden = !table.hidden; plots.hidden = !table.hidden; toggle.textContent = table.hidden ? t('table') : t('chart'); });
  }
  function drawChart(el, spec) {
    if (!el) return;
    const { svg, hits } = plot(spec, width(el), 250);
    const twin = `<table class="twin" hidden><thead><tr><th>${t('model')}</th>${spec.series.map(s => `<th>${s.name()}</th>`).join('')}</tr></thead><tbody>${spec.cats.map((c, i) => `<tr><th>${catName(spec, c)}</th>${spec.series.map(s => `<td>${cell(spec.values[s.key][i], spec)}</td>`).join('')}</tr>`).join('')}</tbody></table>`;
    el.innerHTML = `${legendOf(spec.series)}<div class="plots">${svg}</div><button type="button" class="toggle">${t('table')}</button>${twin}`;
    wire(el, hits);
  }
